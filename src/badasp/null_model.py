def as_bin_threshold_dict(
    threshold: float,
    event_types: Iterable[str],
    bin_intervals: Iterable[pd.Interval],
) -> Dict[Tuple[str, pd.Interval], float]:
    """Build a ``{(event_type, bin_interval): threshold}`` dict for a global threshold.

    Matches the shape produced by `calculate_bin_thresholds` and consumed by
    `identify_switches` in
    ``scripts/plot_decoupled_event_switches_clade_adjusted.py`` exactly
    (tuple key of ``(str, pandas.Interval)`` mapped to a float), so the
    existing switch-calling code can be reused unchanged even though our
    threshold is a single global value rather than a per-(event, bin)
    percentile. Because the threshold is global, every key maps to the same
    value — including ``("overall", interval)`` keys, which is what the
    canonical downstream analyses look up when called with
    ``event_specific=False``.
    """
    groups = list(dict.fromkeys(list(event_types) + ["overall"]))  # de-duplicate, preserve order
    intervals = list(bin_intervals)
    value = float(threshold)
    return {(group, interval): value for group in groups for interval in intervals}
