"""Simulation-calibrated null model for BADASP switch calling.

Background
----------
Each (parent node, child branch, alignment position) gets a score

    score(child) = RC(child) - AC * p_AC(child)

The previous switch-calling rule took the 99.9th percentile of the *observed*
scores within each (event_type x clade-size decile) bin. That is circular: it
manufactures exactly 0.1% "positives" per bin by construction and gives no
error-rate guarantee at all.

This module instead calibrates the threshold against a null generated by
simulating sequence evolution on the *same, fixed* tree under the fitted
substitution model, then re-running the identical ASR + scoring pipeline on
each simulated replicate. Because every replicate is scored with the exact
same tree topology and node names, the null reproduces the identical
(node_name, position) test keys as the observed data, and — crucially — it
reproduces the *dependence structure* between tests (nested clades sharing
leaves, sister branches sharing AC and posteriors, adjacent nodes sharing
subtrees). We never assume independence between tests anywhere in this
module; every guarantee below is either a resampling-based statement that is
valid under arbitrary dependence, or is explicitly flagged as a secondary,
descriptive approximation.

Design decisions carried over from the calling code (not re-litigated here):

* The threshold is GLOBAL across event types (Duplication/Speciation/
  Transfer). The simulator never sees event labels, so conditional on tree
  geometry the null score distribution does not depend on the label; making
  the null event-specific would force equal exceedance rates across D/S/T by
  construction and destroy the event-enrichment signal the study wants to
  measure. `event_type` is used only for reporting, never inside the null.
* The reporting unit is the branch (one score per child per node per
  position). The error-control unit is the node-split: a split is
  "discovered" if EITHER of its two branch scores exceeds the threshold.
  The identical either-branch-exceeds rule is applied when counting null
  exceedances, so that observed and null counts are computed by the same
  procedure.

NaN policy (applies uniformly everywhere in this module)
---------------------------------------------------------
Gap positions in a given branch/replicate produce NaN scores. We adopt one
policy and apply it identically to observed and null data:

* A test's exceedance indicator, ``(left >= t) | (right >= t)``, treats NaN
  branch scores as "does not exceed" — this falls out for free in numpy
  because ``NaN >= t`` is always ``False``. A split with one NaN branch and
  one real branch is therefore still tested on its real branch.
* A split with BOTH branches NaN can never exceed any threshold, in either
  observed or null data, and is therefore silently excluded from every count
  (O(t), V_r(t), exceedance rates) without special-casing — it simply never
  contributes.
* Candidate threshold grids and p-value/quantile computations explicitly
  drop NaN entries before sorting so that NaN does not pollute rank
  statistics (numpy sorts NaN as "largest", which would otherwise corrupt
  counts if not accounted for).

A note on `max(left, right)`
-----------------------------
Internally, several routines compute ``np.fmax(left, right)`` as a single
per-split number. This is used *purely as a monotone computational device*
so that a sort + ``searchsorted``/``cumsum`` can answer "how many splits
have either branch >= t" for every t in one pass. It is mathematically
identical to ``(left >= t) | (right >= t)`` for every threshold t (and
``np.fmax`` inherits the NaN policy above: ``fmax(NaN, x) == x``). It is
never used, reported, or interpreted as a biological "combined score" —
the two branches are the real per-test quantities of interest, and nothing
downstream ever looks at left/right through the lens of "which one was
bigger".
"""

from __future__ import annotations

import warnings
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Sequence, Tuple

import numpy as np
import pandas as pd
from scipy.stats import beta

# Arrays required in every rep_*.npz null-replicate file. See
# `write_null_replicate` / `load_null_scores` docstrings for the exact format.
_NULL_REPLICATE_SCORE_FIELDS = (
    "score_left",
    "score_right",
    "rc_left",
    "rc_right",
    "ac",
    "p_ac_left",
    "p_ac_right",
)
_NULL_REPLICATE_KEY_FIELDS = ("node_name", "position")
_NULL_REPLICATE_OPTIONAL_KEY_FIELDS = ("left_child", "right_child")


# ---------------------------------------------------------------------------
# Null-replicate file I/O
# ---------------------------------------------------------------------------


def write_null_replicate(
    path: Path,
    node_name: Sequence[str],
    position: Sequence[int],
    score_left: Sequence[float],
    score_right: Sequence[float],
    rc_left: Sequence[float],
    rc_right: Sequence[float],
    ac: Sequence[float],
    p_ac_left: Sequence[float],
    p_ac_right: Sequence[float],
    left_child: Optional[Sequence[str]] = None,
    right_child: Optional[Sequence[str]] = None,
) -> None:
    """Write one simulated-replicate file in the ``rep_*.npz`` format.

    File format (this is the canonical definition consumed by
    `load_null_scores`): a ``.npz`` archive containing, on a single shared
    "test" axis of length ``n_tests`` (one entry per (node_name, position)
    scored in that replicate):

    * ``node_name`` (str array) and ``position`` (int array) — the test key.
      Optionally ``left_child`` / ``right_child`` (str arrays) for
      provenance/debugging.
    * ``score_left``, ``score_right``, ``rc_left``, ``rc_right``, ``ac``,
      ``p_ac_left``, ``p_ac_right`` — all float16 arrays of length
      ``n_tests``, matching the columns of ``raw_node_scores.csv``.

    Every replicate written for a given tree/analysis must share the exact
    same key order (same ``node_name``/``position`` at the same array index)
    as every other replicate and as the observed data, since the whole point
    of simulating on the fixed tree is that null and observed tests line up
    one-to-one. `load_null_scores` validates this and fails loudly if it does
    not hold.
    """
    n = len(node_name)
    arrays: Dict[str, np.ndarray] = {
        "node_name": np.asarray(node_name, dtype=str),
        "position": np.asarray(position, dtype=np.int32),
        "score_left": np.asarray(score_left, dtype=np.float16),
        "score_right": np.asarray(score_right, dtype=np.float16),
        "rc_left": np.asarray(rc_left, dtype=np.float16),
        "rc_right": np.asarray(rc_right, dtype=np.float16),
        "ac": np.asarray(ac, dtype=np.float16),
        "p_ac_left": np.asarray(p_ac_left, dtype=np.float16),
        "p_ac_right": np.asarray(p_ac_right, dtype=np.float16),
    }
    for name, arr in arrays.items():
        if arr.shape[0] != n:
            raise ValueError(f"Array '{name}' has length {arr.shape[0]}, expected {n} (from node_name).")
    if left_child is not None:
        arrays["left_child"] = np.asarray(left_child, dtype=str)
    if right_child is not None:
        arrays["right_child"] = np.asarray(right_child, dtype=str)

    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    np.savez(path, **arrays)


def load_null_scores(directory: Path) -> Tuple[np.ndarray, np.ndarray, pd.DataFrame]:
    """Load every ``rep_*.npz`` file in `directory` into stacked null arrays.

    Returns
    -------
    null_left, null_right : np.ndarray, shape (R, n_tests), float32
        Per-replicate branch scores, stacked in file-sort order (R = number
        of replicate files found).
    keys : pd.DataFrame, shape (n_tests, ...)
        The shared test key table (``node_name``, ``position``, and
        ``left_child``/``right_child`` if present), taken from the first
        replicate file.

    All replicates must have identical length and identical key order (see
    `write_null_replicate`); a mismatch raises `ValueError` immediately
    rather than silently truncating or reindexing, since silently
    misaligning null and observed tests would invalidate every downstream
    guarantee in this module.
    """
    directory = Path(directory)
    files = sorted(directory.glob("rep_*.npz"))
    if not files:
        raise FileNotFoundError(f"No 'rep_*.npz' files found in {directory}")

    null_left_chunks: List[np.ndarray] = []
    null_right_chunks: List[np.ndarray] = []
    ref_keys: Optional[pd.DataFrame] = None
    ref_n: Optional[int] = None

    required = set(_NULL_REPLICATE_SCORE_FIELDS) | set(_NULL_REPLICATE_KEY_FIELDS)

    for f in files:
        with np.load(f) as data:
            missing = required - set(data.files)
            if missing:
                raise ValueError(f"Replicate file {f} is missing required arrays: {sorted(missing)}")

            n = data["score_left"].shape[0]
            if ref_n is None:
                ref_n = n
                key_cols = {k: data[k] for k in _NULL_REPLICATE_KEY_FIELDS}
                for k in _NULL_REPLICATE_OPTIONAL_KEY_FIELDS:
                    if k in data.files:
                        key_cols[k] = data[k]
                ref_keys = pd.DataFrame(key_cols)
            elif n != ref_n:
                raise ValueError(
                    f"Replicate {f} has {n} tests but reference replicate {files[0]} has {ref_n}. "
                    "All null replicates must score the identical fixed set of (node, position) tests."
                )
            else:
                if not np.array_equal(data["node_name"], ref_keys["node_name"].to_numpy()) or not np.array_equal(
                    data["position"], ref_keys["position"].to_numpy()
                ):
                    raise ValueError(
                        f"Replicate {f} has a different (node_name, position) key order than reference "
                        f"replicate {files[0]}. Null replicates must be written in a shared, fixed key order."
                    )

            null_left_chunks.append(data["score_left"].astype(np.float32))
            null_right_chunks.append(data["score_right"].astype(np.float32))

    null_left = np.stack(null_left_chunks, axis=0)
    null_right = np.stack(null_right_chunks, axis=0)
    assert ref_keys is not None
    return null_left, null_right, ref_keys


def load_observed_scores(csv_path: Path) -> Tuple[np.ndarray, np.ndarray, pd.DataFrame]:
    """Convenience loader for ``raw_node_scores.csv``.

    Returns ``(obs_left, obs_right, keys)`` where `keys` retains the
    reporting columns (``node_name``, ``event_type``, ``position``,
    ``clade_size_left``, ``clade_size_right``, ``distance_from_root``, ...)
    so callers can join threshold decisions back onto them for reporting.
    """
    df = pd.read_csv(csv_path)
    obs_left = df["badasp_score_left"].to_numpy(dtype=np.float32)
    obs_right = df["badasp_score_right"].to_numpy(dtype=np.float32)
    keys = df.drop(columns=["badasp_score_left", "badasp_score_right"])
    return obs_left, obs_right, keys


# ---------------------------------------------------------------------------
# Core statistic: the either-branch-exceeds rule
# ---------------------------------------------------------------------------


def _split_statistic(left: np.ndarray, right: np.ndarray) -> np.ndarray:
    """Monotone stand-in for the either-branch-exceeds rule.

    ``fmax(left, right) >= t`` is exactly ``(left >= t) | (right >= t)`` for
    every threshold t, including the NaN case (`np.fmax` ignores a single NaN
    operand; a split with both branches NaN yields NaN, and ``NaN >= t`` is
    always False). This lets a single sort answer "how many splits exceed t"
    for every t via `searchsorted`, instead of recomputing the OR at every
    grid point. It is a computational device only, not a reported score.
    """
    return np.fmax(np.asarray(left, dtype=np.float64), np.asarray(right, dtype=np.float64))


