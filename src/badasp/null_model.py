def exceedance_flatness(
    null: np.ndarray,
    covariates: pd.DataFrame,
    threshold: float,
    n_bins: int = 10,
    max_categorical: int = 20,
) -> pd.DataFrame:
    """Realized null exceedance rate per bin of each covariate, at `threshold`.

    For every test, the realized null exceedance rate is
    ``mean_r(null[r, i] >= threshold)`` (NaN null entries never count as
    exceedances, consistent with the module-wide NaN policy). Binning that
    rate by covariates such as log clade size, log sister clade size,
    distance from root, or alignment position and checking whether the rate
    stays flat is the diagnostic for whether a single GLOBAL threshold is
    justified: if the null exceedance rate is flat across bins, one global
    threshold controls the same false-positive rate everywhere and the old
    per-(event_type, clade-size-decile) binning can be retired; if it is not
    flat, conditioning on that covariate is still needed.

    Parameters
    ----------
    null : np.ndarray, shape (R, n_tests)
        Either the per-branch null array or the split-level statistic
        (e.g. from `_split_statistic`) — whichever unit the caller wants the
        diagnostic computed at.
    covariates : pd.DataFrame, shape (n_tests, ...)
        One row per test, aligned by position with `null`'s columns. Pass
        already-transformed columns (e.g. ``np.log(clade_size_left)``) under
        whatever name you want reported.
    threshold : float
        The candidate global threshold being diagnosed.
    n_bins : int
        Number of quantile bins for numeric covariates with more than
        `max_categorical` distinct values.
    max_categorical : int
        Numeric covariates with at most this many distinct values are
        treated as categorical (one bin per value) rather than quantile-binned.

    Returns
    -------
    Tidy long-format DataFrame with columns
    ``covariate, bin_label, mean_exceedance_rate, n_tests, threshold``,
    one row per (covariate, bin).
    """
    null = np.asarray(null, dtype=np.float64)
    if null.shape[1] != len(covariates):
        raise ValueError("covariates must have one row per column of null.")

    with warnings.catch_warnings():
        warnings.simplefilter("ignore", category=RuntimeWarning)
        exceed_rate = np.mean(null >= threshold, axis=0)

    rows = []
    for col in covariates.columns:
        series = covariates[col]
        if pd.api.types.is_numeric_dtype(series) and series.nunique(dropna=True) > max_categorical:
            bins = pd.qcut(series, q=n_bins, duplicates="drop")
        else:
            bins = series.astype("category")

        tmp = pd.DataFrame({"bin": bins, "rate": exceed_rate})
        grouped = tmp.groupby("bin", observed=True)["rate"].agg(["mean", "count"]).reset_index()
        grouped = grouped.rename(columns={"bin": "bin_label", "mean": "mean_exceedance_rate", "count": "n_tests"})
        grouped["covariate"] = col
        grouped["threshold"] = threshold
        rows.append(grouped[["covariate", "bin_label", "mean_exceedance_rate", "n_tests", "threshold"]])

    if not rows:
        return pd.DataFrame(columns=["covariate", "bin_label", "mean_exceedance_rate", "n_tests", "threshold"])
    return pd.concat(rows, ignore_index=True)


